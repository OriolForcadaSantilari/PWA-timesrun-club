const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, es };

const WEEKDAY_KEYS: Record<string, MessageKey> = {
  Monday: "dayMonday",
  Tuesday: "dayTuesday",
  Wednesday: "dayWednesday",
  Thursday: "dayThursday",
  Friday: "dayFriday",
  Saturday: "daySaturday",
  Sunday: "daySunday",
};

const WEEKDAY_SHORT_KEYS: Record<string, MessageKey> = {
  Monday: "dayMonShort",
  Tuesday: "dayTueShort",
  Wednesday: "dayWedShort",
  Thursday: "dayThuShort",
  Friday: "dayFriShort",
  Saturday: "daySatShort",
  Sunday: "daySunShort",
};

export type MessageVars = Record<string, string | number>;

export function localeFromLanguageTag(tag: string | null | undefined): Locale {
  if (!tag) {
    return "en";
  }
  return tag.trim().toLowerCase().startsWith("es") ? "es" : "en";
}

export function localeFromAcceptLanguage(header: string | null | undefined): Locale {
  if (!header) {
    return "en";
  }
  const first = header.split(",")[0]?.split(";")[0]?.trim() ?? "";
  return localeFromLanguageTag(first);
}

export function translate(locale: Locale, key: MessageKey, vars?: MessageVars): string {
  const template = dictionaries[locale][key] ?? dictionaries.en[key];
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name]),
  );
}

export function weekdayLabel(locale: Locale, englishDay: string): string {
  const key = WEEKDAY_KEYS[englishDay];
  return key ? translate(locale, key) : englishDay;
}

export function weekdayShortLabel(locale: Locale, englishDay: string): string {
  const key = WEEKDAY_SHORT_KEYS[englishDay];
  return key ? translate(locale, key) : englishDay;
}

